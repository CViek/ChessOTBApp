"""Write only public client configuration; never bundle local backend secret keys."""
import json
from pathlib import Path
status = json.loads(Path('.supabase/status.json').read_text())
values = status.get('env', status)
url = values.get('API_URL') or values.get('api_url')
key = values.get('PUBLISHABLE_KEY') or values.get('publishable_key')
if not url or not key or not key.startswith('sb_publishable_'):
    raise SystemExit('Could not find the local API URL and publishable key in Supabase status.')
# xcconfig uses // as a comment delimiter. Expand an empty build variable between slashes.
url = url.replace('://', ':/$()/')
Path('Config/Local.xcconfig').write_text(
    '// Generated by tools/backend/start-local.sh; ignored by Git.\n'
    f'SUPABASE_URL = {url}\nSUPABASE_PUBLISHABLE_KEY = {key}\nCHESSOTB_LOCAL_TESTS = YES\n'
)
print('Configured the iOS Debug build for the local Supabase backend.')
